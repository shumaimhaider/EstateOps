import { EntitySchema } from 'typeorm';

export const UnitRow = new EntitySchema({
  name: 'UnitRow',
  tableName: 'unit',
  schema: 'inventory',
  columns: {
    id: { type: 'uuid', primary: true },
    tenant_id: { type: 'uuid' },
    project_id: { type: 'uuid' },
    phase_id: { type: 'uuid', nullable: true },
    block_id: { type: 'uuid', nullable: true },
    floor_id: { type: 'uuid', nullable: true },
    unit_no: { type: 'text' },
    kind: { type: 'text' },
    area_value: { type: 'numeric', precision: 14, scale: 2 },
    area_unit: { type: 'text' },
    bedrooms: { type: 'int', nullable: true },
    facing: { type: 'text', nullable: true },
    view: { type: 'text', nullable: true },
    corner: { type: 'boolean' },
    parking: { type: 'int' },
    attributes: { type: 'jsonb' },
    status: { type: 'text' },
    list_price: { type: 'bigint' },
    currency: { type: 'char', length: 3 },
    geometry: { type: 'jsonb', nullable: true },
    booking_id: { type: 'uuid', nullable: true },
    ever_booked: { type: 'boolean' },
    created_by: { type: 'uuid', nullable: true },
    created_at: { type: 'timestamptz', insert: false, update: false },
    updated_at: { type: 'timestamptz', insert: false },
    version: { type: 'int', insert: false },
  },
});
